/**
 * Builds the Netlify `_headers`, `robots.txt` and `sitemap.xml` files.
 * Pure functions so they can be unit tested; called from vite.config.js.
 *
 * The Content-Security-Policy is deliberately explicit: it allows only this
 * site, this project's own Supabase origins, and Calendly (the booking
 * provider). Nothing is wildcarded except Calendly's own subdomains.
 */

const DEFAULT_SITE_URL = 'https://hyrumhaircuts.com';

/** @param {string | undefined} supabaseUrl */
export function supabaseOrigins(supabaseUrl) {
  if (!supabaseUrl) return { api: [], realtime: [], storage: [], isHttps: true };
  let url;
  try {
    url = new URL(supabaseUrl);
  } catch {
    throw new Error(`VITE_SUPABASE_URL is not a valid URL: ${supabaseUrl}`);
  }
  const api = [url.origin];
  const realtime = [`${url.protocol === 'https:' ? 'wss' : 'ws'}://${url.host}`];
  // Resumable (TUS) video uploads go to the direct Storage hostname.
  const storage = [];
  if (url.hostname.endsWith('.supabase.co')) {
    const ref = url.hostname.slice(0, -'.supabase.co'.length);
    storage.push(`https://${ref}.storage.supabase.co`);
  }
  return { api, realtime, storage, isHttps: url.protocol === 'https:' };
}

/** @param {string | undefined} supabaseUrl */
export function buildCsp(supabaseUrl) {
  const s = supabaseOrigins(supabaseUrl);
  const calendly = ['https://calendly.com', 'https://*.calendly.com'];
  const join = (...parts) => parts.flat().filter(Boolean).join(' ');

  const directives = [
    "default-src 'self'",
    `script-src ${join("'self'", 'https://assets.calendly.com')}`,
    `style-src ${join("'self'", 'https://assets.calendly.com')}`,
    `img-src ${join("'self'", 'data:', 'blob:', s.api, calendly)}`,
    `media-src ${join("'self'", 'blob:', s.api)}`,
    `font-src ${join("'self'", 'https://assets.calendly.com')}`,
    `connect-src ${join("'self'", s.api, s.realtime, s.storage, calendly)}`,
    `frame-src ${join(calendly)}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ];
  if (s.isHttps) directives.push('upgrade-insecure-requests');
  return directives.join('; ');
}

/**
 * The same policy for a <meta http-equiv> tag (static hosts such as GitHub
 * Pages cannot send headers). Browsers ignore frame-ancestors in a meta tag,
 * so it is left out here; the admin protects itself against framing in JS.
 * @param {string | undefined} supabaseUrl
 */
export function buildMetaCsp(supabaseUrl) {
  return buildCsp(supabaseUrl)
    .split('; ')
    .filter((d) => !d.startsWith('frame-ancestors'))
    .join('; ');
}

/**
 * @param {string | undefined} supabaseUrl
 * @param {{ indexable?: boolean }} [options] indexable=false for deploy previews and branch deploys
 */
export function buildHeaders(supabaseUrl, { indexable = true } = {}) {
  const csp = buildCsp(supabaseUrl);
  const robots = indexable ? '' : '  X-Robots-Tag: noindex, nofollow, noarchive\n';
  return `# Generated by scripts/netlify-headers.js at build time. Do not edit by hand.
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Content-Security-Policy: ${csp}
${robots}
# The admin is never indexed and never cached, so a signed-out browser cannot
# be handed a stale copy of it.
/admin
  X-Robots-Tag: noindex, nofollow, noarchive
  Cache-Control: no-store
/admin/*
  X-Robots-Tag: noindex, nofollow, noarchive
  Cache-Control: no-store

# Thank-you page is not a landing page.
/booking/thanks/*
  X-Robots-Tag: noindex

# Fingerprinted build output never changes, so it can be cached forever.
/build/*
  Cache-Control: public, max-age=31536000, immutable

# Images and the fallback video: cache for a day, revalidate after.
/assets/*
  Cache-Control: public, max-age=86400
`;
}

/** @param {string | undefined} siteUrl */
export function buildRobots(siteUrl, { indexable = true } = {}) {
  const base = (siteUrl || DEFAULT_SITE_URL).replace(/\/+$/, '');
  // Deploy previews and branch deploys must never be crawled.
  if (!indexable) return 'User-agent: *\nDisallow: /\n';
  return `User-agent: *
Allow: /
Disallow: /admin/
Disallow: /booking/thanks/

Sitemap: ${base}/sitemap.xml
`;
}

/** @param {string | undefined} siteUrl */
export function buildSitemap(siteUrl) {
  const base = (siteUrl || DEFAULT_SITE_URL).replace(/\/+$/, '');
  const urls = ['/', '/booking/', '/privacy/'];
  const body = urls.map((p) => `  <url><loc>${base}${p}</loc></url>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;
}
